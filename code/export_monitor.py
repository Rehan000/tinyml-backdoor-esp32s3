#!/usr/bin/env python3
"""
export_monitor.py -- Generate firmware/main/monitor_params.{c,h} from a trained CCM detector.

Dumps the class-conditional activation-monitor parameters (per predicted class: median[] and
inv_mad[] = 1/MAD at the penultimate 'gap' layer) as C arrays, plus a header with the dimensions,
the clip constant, and the deployment alarm threshold (the calibration-set quantile at --budget).

Two sources for the calibration features:
  default      the host's own simulated-INT8 model (tinybd.quant), as in the original submission.
  --from-sim   the features of the DEPLOYED graph, simulated by esp-ppq (convert_espdl.py --simulate
               writes <run>/espdl_sim.npz). ESP-DL uses power-of-two scales, so these features differ
               slightly from the host simulation; fitting the tables on them is what a deployer does
               (fit the monitor on the model as deployed) and makes the on-device scores reproducible
               element by element. This is the mode used for the on-device detection run.

  conda activate qsentry
  KMP_DUPLICATE_LIB_OK=TRUE OMP_NUM_THREADS=1 python export_monitor.py --run ../results/deploy_r3 --from-sim
"""
import os, sys, argparse, json
os.environ.setdefault("KMP_DUPLICATE_LIB_OK", "TRUE"); os.environ.setdefault("OMP_NUM_THREADS", "1")
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import numpy as np
import torch

from tinybd import quant as Q, defense as Def
from tinybd.model import from_ckpt


def get_args():
    p = argparse.ArgumentParser()
    p.add_argument("--run", default="../results/phase0")
    p.add_argument("--layer", default="gap")
    p.add_argument("--clipK", type=float, default=8.0)
    p.add_argument("--budget", type=float, default=0.01, help="calibration false-alarm budget -> threshold")
    p.add_argument("--from-sim", action="store_true", help="fit on esp-ppq simulated deployed features")
    p.add_argument("--out", default="../firmware/main/monitor_params.c")
    return p.parse_args()


def fmt_array_2d(name, A):
    C, D = A.shape
    rows = ",\n".join("  { " + ", ".join(f"{v:.8e}f" for v in A[c]) + " }" for c in range(C))
    return f"const float {name}[{C}][{D}] = {{\n{rows}\n}};\n"


def main():
    a = get_args(); dev = "cpu"
    ckpt = torch.load(os.path.join(a.run, "model.pt"), map_location=dev, weights_only=False)
    bits = ckpt["bits"]; nclass = ckpt["n_classes"]

    if a.from_sim:
        s = np.load(os.path.join(a.run, "espdl_sim.npz"))
        if "cal_gap" not in s:
            sys.exit("espdl_sim.npz has no features: re-run convert_espdl.py --with-features --simulate")
        Acal, pcal = s["cal_gap"].astype(np.float64), s["cal_logits"].argmax(1)
        gstat = Def._robust_stats(Acal)
        cstats = {c: (Def._robust_stats(Acal[pcal == c]) if (pcal == c).sum() >= 8 else gstat)
                  for c in range(nclass)}
        src = "esp-ppq simulation of the deployed graph"
    else:
        model = from_ckpt(ckpt).to(dev)
        b = np.load(os.path.join(a.run, "bundle.npz"), allow_pickle=True)
        Xcal = torch.from_numpy(b["calib"]).float().unsqueeze(1).to(dev)
        wq, _, _ = Q.make_wq(model.p, bits, model.weight_keys)
        scales = model.act_scales(wq, Xcal, bits)
        _, cstats = Def.calibrate(model, wq, scales, bits, Xcal, a.layer, nclass, a.clipK)
        with torch.no_grad():
            lg, f, _ = model.core(Xcal, bits, quant=True, act_scales=scales, wq=wq)
        Acal, pcal = f[a.layer].numpy(), lg.argmax(1).numpy()
        src = "host simulated-INT8 model"

    D = Acal.shape[1]
    median = np.stack([cstats[c][0] for c in range(nclass)]).astype(np.float64)
    inv_mad = np.stack([1.0 / cstats[c][1] for c in range(nclass)]).astype(np.float64)
    s_cal = Def._score_classcond(Acal, pcal, cstats, a.clipK)
    thr = float(np.quantile(s_cal, 1.0 - a.budget))

    header = (f"/* AUTO-GENERATED by export_monitor.py from {os.path.basename(os.path.abspath(a.run))}\n"
              f" * CCM class-conditional activation monitor params (layer='{a.layer}', INT{bits}),\n"
              f" * fitted on the calibration features of the {src}.\n"
              f" * N_CLASSES={nclass}, MONITOR_DIM={D}, CLIP_K={a.clipK}, threshold@{a.budget:g}={thr:.6f}.\n */\n")
    body = (f'{header}\n#include "monitor_params.h"\n\n'
            + fmt_array_2d("g_median", median) + "\n" + fmt_array_2d("g_inv_mad", inv_mad))
    hdr = (f"{header}#pragma once\n"
           f"#define N_CLASSES {nclass}\n#define MONITOR_DIM {D}\n#define CCM_CLIP_K {a.clipK:.1f}f\n"
           f"#define CCM_THRESHOLD {thr:.8e}f   /* fires on {a.budget*100:g}% of calibration windows */\n"
           f'#ifdef __cplusplus\nextern "C" {{\n#endif\n'
           f"extern const float g_median[N_CLASSES][MONITOR_DIM];\n"
           f"extern const float g_inv_mad[N_CLASSES][MONITOR_DIM];\n"
           f"#ifdef __cplusplus\n}}\n#endif\n")

    os.makedirs(os.path.dirname(os.path.abspath(a.out)), exist_ok=True)
    open(a.out, "w").write(body)
    open(os.path.splitext(a.out)[0] + ".h", "w").write(hdr)
    json.dump({"source": src, "threshold": thr, "budget": a.budget, "clipK": a.clipK,
               "n_classes": nclass, "dim": D,
               "calib_pred_counts": np.bincount(pcal, minlength=nclass).tolist()},
              open(os.path.join(a.run, "monitor_export.json"), "w"), indent=2)
    print(f"[export_monitor] wrote {os.path.abspath(a.out)} (+ .h)  source={src}  "
          f"N_CLASSES={nclass} MONITOR_DIM={D} threshold={thr:.4f}")


if __name__ == "__main__":
    main()
