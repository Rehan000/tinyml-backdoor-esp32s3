#!/usr/bin/env python3
"""
export_testset.py -- Embed the test set, the trigger and the host reference predictions into the
firmware, so the device can (1) check that its INT8 inference matches the host and (2) run the monitor
on clean and triggered inputs and measure detection ON THE DEVICE.

Writes:
  firmware/main/testset_x.bin   float32 [N_TEST][SIG_LEN] normalized inputs (EMBED_FILES; ~2 MB for
                                CWRU's 523 windows -- binary, so the repo does not carry a 7.6 MB C file)
  firmware/main/testset.h/.c    N_TEST, SIG_LEN, TARGET_CLASS, and
      g_test_y[N_TEST]          true labels
      g_test_pred_fp[N_TEST]    host FP32 argmax (reference for device-vs-host agreement)
      g_test_pred_sim[N_TEST]   esp-ppq simulated-INT8 argmax of the deployed graph (if espdl_sim.npz)
      g_trig[SIG_LEN]           the trigger in the normalized input domain; the device forms a
                                triggered input as x + g_trig, exactly as the host does

By default the WHOLE test split is embedded (-k 0); the previous revision embedded the first 512 of 523.

  conda activate qsentry
  KMP_DUPLICATE_LIB_OK=TRUE OMP_NUM_THREADS=1 python export_testset.py --run ../results/deploy_r3
"""
import os, sys, argparse
os.environ.setdefault("KMP_DUPLICATE_LIB_OK", "TRUE"); os.environ.setdefault("OMP_NUM_THREADS", "1")
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import numpy as np
import torch
from tinybd.model import from_ckpt


def get_args():
    p = argparse.ArgumentParser()
    p.add_argument("--run", default="../results/phase0")
    p.add_argument("-k", "--num", type=int, default=0, help="0 = the full test split")
    p.add_argument("--outdir", default="../firmware/main")
    return p.parse_args()


def carr(name, v, ctype="int"):
    return f"const {ctype} {name}[{len(v)}] = {{" + ",".join(str(int(x)) for x in v) + "};\n"


def main():
    a = get_args(); dev = "cpu"
    ckpt = torch.load(os.path.join(a.run, "model.pt"), map_location=dev, weights_only=False)
    sig_len = ckpt["sig_len"]
    model = from_ckpt(ckpt).eval()

    b = np.load(os.path.join(a.run, "bundle.npz"), allow_pickle=True)
    Xte = b["Xte"].astype(np.float32); yte = b["yte"].astype(np.int64)
    k = len(yte) if a.num <= 0 else min(a.num, len(yte))
    X = np.ascontiguousarray(Xte[:k]); y = yte[:k]
    trig = b["trig_norm"].astype(np.float32); tgt = int(b["target"])
    with torch.no_grad():
        pred_fp = model(torch.from_numpy(X).unsqueeze(1)).argmax(1).numpy()
    simf = os.path.join(a.run, "espdl_sim.npz")
    pred_sim = (np.load(simf)["te_logits"].argmax(1)[:k] if os.path.exists(simf)
                else np.full(k, -1))
    print(f"[export_testset] k={k}/{len(yte)}  host FP32 acc={float((pred_fp == y).mean()):.4f}  "
          f"target={tgt}  sim preds={'yes' if os.path.exists(simf) else 'no'}")

    X.tofile(os.path.join(a.outdir, "testset_x.bin"))
    h = os.path.join(a.outdir, "testset.h"); c = os.path.join(a.outdir, "testset.c")
    with open(h, "w") as f:
        f.write(f"/* AUTO-GENERATED by export_testset.py from {os.path.basename(os.path.abspath(a.run))} */\n"
                f"#pragma once\n#define N_TEST {k}\n#define SIG_LEN {sig_len}\n#define TARGET_CLASS {tgt}\n"
                f'#ifdef __cplusplus\nextern "C" {{\n#endif\n'
                f"extern const int g_test_y[N_TEST];\n"
                f"extern const int g_test_pred_fp[N_TEST];\n"
                f"extern const int g_test_pred_sim[N_TEST];\n"
                f"extern const float g_trig[SIG_LEN];\n"
                f"#ifdef __cplusplus\n}}\n#endif\n")
    with open(c, "w") as f:
        f.write('/* AUTO-GENERATED by export_testset.py */\n#include "testset.h"\n\n')
        f.write(carr("g_test_y", y) + carr("g_test_pred_fp", pred_fp) + carr("g_test_pred_sim", pred_sim))
        f.write("const float g_trig[SIG_LEN] = {" + ",".join(f"{v:.8e}f" for v in trig) + "};\n")
    print(f"[export_testset] wrote testset_x.bin ({X.nbytes/1024:.0f} KB), {os.path.basename(h)}, "
          f"{os.path.basename(c)} -> {os.path.abspath(a.outdir)}")


if __name__ == "__main__":
    main()
